const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const test = require('node:test')
const { SYNC_DEBOUNCE_MS, SYNC_INTERVAL_MS, planSync } = require('./syncSchedule')

test('sync runs on launch, a 2 minute interval, 10 seconds after a change, now, and quit', () => {
  assert.equal(SYNC_INTERVAL_MS, 120000)
  assert.equal(SYNC_DEBOUNCE_MS, 10000)
  assert.deepEqual(planSync('launch'), { run: true, delayMs: 0 })
  assert.deepEqual(planSync('interval'), { run: true, delayMs: 120000 })
  assert.deepEqual(planSync('change'), { run: true, delayMs: 10000 })
  assert.deepEqual(planSync('watch'), { run: true, delayMs: 10000 })
  assert.deepEqual(planSync('now'), { run: true, delayMs: 0 })
  assert.deepEqual(planSync('quit'), { run: true, delayMs: 0 })
})

test('the desktop shell schedules sync and keeps the OneDrive refresh token out of the page', () => {
  const main = fs.readFileSync(path.join(__dirname, 'main.js'), 'utf8')
  const preload = fs.readFileSync(path.join(__dirname, 'preload.js'), 'utf8')
  const pkg = require('./package.json')
  assert.match(main, /eq:sync-touch/)
  assert.match(main, /eq:pick-sync-folder/)
  assert.match(main, /eq:onedrive-sign-in/)
  assert.match(main, /eq:onedrive-sign-out/)
  assert.match(main, /planSync\('launch'\)|scheduleSync\('launch'\)/)
  assert.match(main, /SYNC_INTERVAL_MS/)
  assert.match(main, /runSync\('quit'\)/)
  assert.match(main, /safeStorage/)
  assert.equal(main.includes('refresh_token'), false)
  assert.match(preload, /syncTouch/)
  assert.match(preload, /pickSyncFolder/)
  assert.match(preload, /signInOneDrive/)
  assert.match(preload, /signOutOneDrive/)
  assert.equal(preload.includes('refresh_token'), false)
  assert.ok(pkg.build.files.includes('onedriveAuth.js'))
  assert.ok(pkg.build.files.includes('syncSchedule.js'))
})
