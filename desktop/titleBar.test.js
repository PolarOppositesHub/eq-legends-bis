const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const test = require('node:test')
const { TITLEBAR_DOUBLE_CLICK, mainWindowChrome, windowControlCall } = require('./titleBar')

test('the main window is frameless and keeps Windows snap without a second caption', () => {
  const chrome = mainWindowChrome()
  assert.equal(chrome.frame, false)
  assert.equal(chrome.thickFrame, true)
  assert.equal(chrome.titleBarOverlay, false)
  assert.equal(chrome.minimizable, true)
  assert.equal(chrome.maximizable, true)
  assert.equal(chrome.closable, true)
  assert.equal(TITLEBAR_DOUBLE_CLICK, 'native-drag-region')
  assert.equal(windowControlCall('minimize', false), 'minimize')
  assert.equal(windowControlCall('toggle-maximize', false), 'maximize')
  assert.equal(windowControlCall('toggle-maximize', true), 'unmaximize')
  assert.equal(windowControlCall('close', false), 'close')
})

test('caption buttons use the existing close path and the page draws the bar', () => {
  const main = fs.readFileSync(path.join(__dirname, 'main.js'), 'utf8')
  const preload = fs.readFileSync(path.join(__dirname, 'preload.js'), 'utf8')
  const pkg = require('./package.json')
  assert.match(main, /mainWindowChrome\(/)
  assert.match(main, /eq:window-minimize/)
  assert.match(main, /eq:window-toggle-maximize/)
  assert.match(main, /eq:window-close/)
  assert.match(main, /windowControlCall\('close'/)
  assert.match(main, /mainWindow\.close\(\)/)
  assert.match(main, /shouldMinimizeToTray/)
  assert.equal(main.includes('frame: true'), false)
  assert.match(preload, /windowMinimize/)
  assert.match(preload, /windowToggleMaximize/)
  assert.match(preload, /windowClose/)
  assert.ok(pkg.build.files.includes('titleBar.js'))
})
